#!/bin/sh
# Runs INSIDE an alpine linux/arm/v7 container (see vm/build.sh).
# Produces a "Kindle-like host" root filesystem + kernel for qemu-system-arm:
#   /out/vmlinuz, /out/initramfs, /out/host.img (ext4), /out/userstore.img (vfat)
#
# The host deliberately mimics what matters on a Paperwhite 6 (2024):
#   - armv7 / armhf userspace, 2 cores, ~474 MB visible RAM, 128 MB zram swap
#   - an X server on :0 at 1272x1696, 8-bit StaticGray (like the device), driven by awesome, with a lab126-style
#     window-title parser (L:A / L:D / L:C layers, clients can't resize themselves)
#   - /mnt/us is a FAT32 "userstore"; images there are loop-mounted like on device
#   - stubs for initctl / lipc-get-prop / lipc-set-prop / eips so Kindle scripts
#     run unmodified
#   - a "framework" memory ballast that grows/shrinks when lab126_gui is
#     started/stopped, so browsers see the same RAM pressure as on the device
set -eu

ALPINE_BRANCH="${ALPINE_BRANCH:-v3.23}"
HOST_SIZE_MB="${HOST_SIZE_MB:-2048}"
USERSTORE_SIZE_MB="${USERSTORE_SIZE_MB:-3072}"
ROOT=/build/host
MIRROR=https://dl-cdn.alpinelinux.org/alpine

apk add --no-cache e2fsprogs dosfstools mtools >/dev/null

rm -rf "$ROOT"; mkdir -p "$ROOT/etc/apk"
printf '%s\n' "$MIRROR/$ALPINE_BRANCH/main" "$MIRROR/$ALPINE_BRANCH/community" > "$ROOT/etc/apk/repositories"
cp -r /etc/apk/keys "$ROOT/etc/apk/"

echo ">> installing host packages"
apk --root "$ROOT" --initdb --update-cache --arch armv7 add \
  alpine-base linux-lts linux-firmware-none busybox-openrc openssh-server e2fsprogs util-linux-misc \
  procps-ng htop dbus dbus-x11 eudev udev-init-scripts udev-init-scripts-openrc \
  xorg-server xf86-input-libinput xinit xset xrandr awesome \
  xdotool xprop xwininfo xdpyinfo xinput xev xwd xvfb x11vnc imagemagick \
  font-dejavu >/dev/null

du -sh "$ROOT"; echo ">> overlay"
cp -a /work/vm/overlay/. "$ROOT/"
chmod +x "$ROOT"/usr/local/bin/* "$ROOT"/usr/local/sbin/* "$ROOT"/etc/init.d/kindle-* 2>/dev/null || true

# --- base system config -------------------------------------------------------
echo kindle-vm > "$ROOT/etc/hostname"
cat > "$ROOT/etc/fstab" <<'EOF'
LABEL=kindle-root  /  ext4  rw,noatime  0 1
LABEL=Kindle  /mnt/us  vfat  rw,noatime,utf8,shortname=mixed,uid=0,gid=0,umask=000  0 0
tmpfs     /tmp     tmpfs rw,nosuid,nodev,size=64m  0 0
EOF
mkdir -p "$ROOT/mnt/us" "$ROOT/var/local/kmc"
cat > "$ROOT/etc/network/interfaces" <<'EOF'
auto lo
iface lo inet loopback
auto eth0
iface eth0 inet dhcp
EOF
# Serial console login (root, no password) - it's a throwaway test VM.
sed -i 's/^tty[2-6]/#&/' "$ROOT/etc/inittab"
echo 'ttyAMA0::respawn:/sbin/getty -L 115200 ttyAMA0 vt100' >> "$ROOT/etc/inittab"
sed -i 's/^root:[^:]*:/root::/' "$ROOT/etc/shadow"

# sshd: key-only root login with the key generated by vm/build.sh
mkdir -p "$ROOT/root/.ssh"
cp /work/vm/out/id_ed25519.pub "$ROOT/root/.ssh/authorized_keys"
chmod 700 "$ROOT/root/.ssh"; chmod 600 "$ROOT/root/.ssh/authorized_keys"
sed -i 's/^#\?PermitRootLogin.*/PermitRootLogin prohibit-password/' "$ROOT/etc/ssh/sshd_config"

for s in devfs dmesg udev udev-trigger udev-settle; do ln -sf /etc/init.d/$s "$ROOT/etc/runlevels/sysinit/$s"; done
for s in modules sysctl hostname bootmisc syslog localmount networking; do ln -sf /etc/init.d/$s "$ROOT/etc/runlevels/boot/$s"; done
for s in sshd dbus kindle-sim kindle-x; do ln -sf /etc/init.d/$s "$ROOT/etc/runlevels/default/$s"; done
for s in mount-ro killprocs savecache; do ln -sf /etc/init.d/$s "$ROOT/etc/runlevels/shutdown/$s"; done
printf '%s\n' virtio_mmio virtio_net virtio_rng virtio_gpu virtio_input evdev zram loop vfat nls_cp437 nls_iso8859_1 > "$ROOT/etc/modules"

# --- kernel + initramfs --------------------------------------------------------
cat > "$ROOT/etc/mkinitfs/mkinitfs.conf" <<'EOF'
features="base ext4 virtio"
EOF
KVER="$(ls "$ROOT/lib/modules" | head -1)"
echo ">> mkinitfs $KVER"
chroot "$ROOT" mkinitfs -o /boot/initramfs-lts "$KVER" >/dev/null
cp "$ROOT/boot/vmlinuz-lts" /out/vmlinuz
cp "$ROOT/boot/initramfs-lts" /out/initramfs

# --- disks ---------------------------------------------------------------------
echo ">> host.img (${HOST_SIZE_MB} MB ext4)"
rm -f /out/host.img
mkfs.ext4 -q -L kindle-root -d "$ROOT" /out/host.img "${HOST_SIZE_MB}M"

if [ ! -f /out/userstore.img ] || [ "${REBUILD_USERSTORE:-0}" = 1 ]; then
  echo ">> userstore.img (${USERSTORE_SIZE_MB} MB FAT32, like /mnt/us on the device)"
  rm -f /out/userstore.img
  truncate -s "${USERSTORE_SIZE_MB}M" /out/userstore.img
  mkfs.vfat -F 32 -n Kindle /out/userstore.img >/dev/null
  export MTOOLS_SKIP_CHECK=1
  mmd -i /out/userstore.img ::/documents ::/extensions ::/kmc
else
  echo ">> keeping existing userstore.img (REBUILD_USERSTORE=1 to recreate)"
fi
echo ">> done"
ls -la /out
